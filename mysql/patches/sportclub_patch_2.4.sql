-- ##########################################################
-- # Cups: Every cup has its own page and theme. A cup has  #
-- # seasons, every season has races (Eventor or manual),   #
-- # results and reports (with images).                     #
-- # The point system, categories and other rules of a      #
-- # season are stored as JSON in CUP_SEASON.SETTINGS, the  #
-- # standings are calculated in the browser so that a      #
-- # changed point system is reflected directly.            #
-- # CUP_RACE.EVENT_ID links a race to a race the club has  #
-- # imported (RACE_EVENT). It is set from the result       #
-- # import, and the club members results are then saved   #
-- # to the cup automatically. Not a foreign key, since the #
-- # result import recreates RACE_EVENT with a new id.      #
-- ##########################################################

CREATE TABLE IF NOT EXISTS CUP
(
    CUP_ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    NAME VARCHAR(128) NOT NULL,
    SLUG VARCHAR(64) NOT NULL,
    DESCRIPTION TEXT,
    THEME VARCHAR(16) NOT NULL DEFAULT 'SUMMER',
    PRIMARY_COLOR VARCHAR(16),
    SECONDARY_COLOR VARCHAR(16),
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    SHOW_IN_TOOLBAR BOOLEAN NOT NULL DEFAULT FALSE,
    CRE_BY_USER_ID INT UNSIGNED NOT NULL DEFAULT 0,
    CRE_DATE DATETIME NOT NULL,
    MOD_BY_USER_ID INT UNSIGNED NOT NULL DEFAULT 0,
    MOD_DATE DATETIME NOT NULL,
    PRIMARY KEY (CUP_ID),
    UNIQUE INDEX IDX_CUP_SLUG (SLUG)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS CUP_SEASON
(
    SEASON_ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    CUP_ID INT UNSIGNED NOT NULL,
    NAME VARCHAR(64) NOT NULL,
    START_DATE DATE NOT NULL,
    END_DATE DATE NOT NULL,
    SETTINGS TEXT NOT NULL,
    PRIMARY KEY (SEASON_ID),
    INDEX IDX_CUP_SEASON_CUP (CUP_ID),
    CONSTRAINT FK_CUP_SEASON_CUP FOREIGN KEY (CUP_ID)
    REFERENCES CUP(CUP_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS CUP_RACE
(
    CUP_RACE_ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    SEASON_ID INT UNSIGNED NOT NULL,
    NAME VARCHAR(128) NOT NULL,
    RACE_DATE DATE NOT NULL,
    EVENTOR_ID INT UNSIGNED,
    EVENTOR_RACE_ID INT UNSIGNED,
    USE_TOTAL_RESULT BOOLEAN NOT NULL DEFAULT FALSE,
    THEME VARCHAR(16),
    EVENT_ID INT UNSIGNED,
    PRIMARY KEY (CUP_RACE_ID),
    INDEX IDX_CUP_RACE_SEASON (SEASON_ID),
    INDEX IDX_CUP_RACE_EVENT (EVENT_ID),
    CONSTRAINT FK_CUP_RACE_SEASON FOREIGN KEY (SEASON_ID)
    REFERENCES CUP_SEASON(SEASON_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS CUP_RACE_RESULTS
(
    CUP_RESULT_ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    CUP_RACE_ID INT UNSIGNED NOT NULL,
    COMPETITOR_ID INT UNSIGNED,
    EVENTOR_PERSON_ID INT UNSIGNED,
    PERSON_NAME VARCHAR(256) NOT NULL,
    BIRTH_YEAR INT,
    CLUB_NAME VARCHAR(128),
    IS_CLUB_MEMBER BOOLEAN NOT NULL DEFAULT FALSE,
    CLASS_NAME VARCHAR(64) NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    POSITION INT,
    TIME_SECONDS INT,
    TIME_BEHIND_SECONDS INT,
    NOF_STARTS_IN_CLASS INT,
    SOURCE VARCHAR(16) NOT NULL DEFAULT 'MANUAL',
    PRIMARY KEY (CUP_RESULT_ID),
    INDEX IDX_CUP_RACE_RESULTS_RACE (CUP_RACE_ID),
    CONSTRAINT FK_CUP_RACE_RESULTS_RACE FOREIGN KEY (CUP_RACE_ID)
    REFERENCES CUP_RACE(CUP_RACE_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- A report with CUP_RACE_ID NULL is a report for the whole season
CREATE TABLE IF NOT EXISTS CUP_REPORTS
(
    REPORT_ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    SEASON_ID INT UNSIGNED NOT NULL,
    CUP_RACE_ID INT UNSIGNED,
    HEADER VARCHAR(128) NOT NULL,
    INTRODUCTION TEXT,
    TEXT MEDIUMTEXT,
    CRE_BY_USER_ID INT UNSIGNED NOT NULL DEFAULT 0,
    CRE_DATE DATETIME NOT NULL,
    MOD_BY_USER_ID INT UNSIGNED NOT NULL DEFAULT 0,
    MOD_DATE DATETIME NOT NULL,
    PRIMARY KEY (REPORT_ID),
    INDEX IDX_CUP_REPORTS_SEASON (SEASON_ID),
    CONSTRAINT FK_CUP_REPORTS_SEASON FOREIGN KEY (SEASON_ID)
    REFERENCES CUP_SEASON(SEASON_ID) ON DELETE CASCADE,
    INDEX IDX_CUP_REPORTS_RACE (CUP_RACE_ID),
    CONSTRAINT FK_CUP_REPORTS_RACE FOREIGN KEY (CUP_RACE_ID)
    REFERENCES CUP_RACE(CUP_RACE_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- The images are stored in the files table, in the news folder (folder_id = 1)
CREATE TABLE IF NOT EXISTS CUP_REPORT_FILES
(
    REPORT_ID INT UNSIGNED NOT NULL,
    FILE_ID INT UNSIGNED NOT NULL,
    ORDER_FIELD INT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (REPORT_ID, FILE_ID),
    INDEX IDX_CUP_REPORT_FILES_FILE (FILE_ID),
    CONSTRAINT FK_CUP_REPORT_FILES_REPORT FOREIGN KEY (REPORT_ID)
    REFERENCES CUP_REPORTS(REPORT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_CUP_REPORT_FILES_FILE FOREIGN KEY (FILE_ID)
    REFERENCES files(file_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
