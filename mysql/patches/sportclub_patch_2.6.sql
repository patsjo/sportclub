-- ##########################################################
-- # Invoices that are paid with Swish on the web page.     #
-- # INVOICE_BATCHES  the same invoice to many (e.g.        #
-- #                  "Medlemsavgift 2026"), BATCH_TYPE     #
-- #                  GENERAL or EVENT_FEES (with the       #
-- #                  invoiced period, no overlap or gap).  #
-- # INVOICES         one per recipient: a user, a          #
-- #                  competitor or a family. STATUS        #
-- #                  UNPAID, PAID, OVERPAID or CANCELLED.  #
-- # INVOICE_ROWS     the specification, e.g. the races.   #
-- # INVOICE_HISTORY  every change of the status, by whom  #
-- #                  (CHANGED_BY_USER_ID NULL = Swish).    #
-- # SWISH_PAYMENTS   the payment requests sent to Swish.  #
-- ##########################################################

CREATE TABLE IF NOT EXISTS INVOICE_BATCHES
(
    BATCH_ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    BATCH_TYPE VARCHAR(16) NOT NULL DEFAULT 'GENERAL',
    TITLE VARCHAR(128) NOT NULL,
    MESSAGE_TEMPLATE VARCHAR(128) NOT NULL,
    INVOICE_DATE DATE NOT NULL,
    DUE_DATE DATE NOT NULL,
    PERIOD_FROM DATE DEFAULT NULL,
    PERIOD_TO DATE DEFAULT NULL,
    CRE_BY_USER_ID INT UNSIGNED NOT NULL,
    CRE_DATE DATETIME NOT NULL,
    PRIMARY KEY (BATCH_ID),
    INDEX IDX_INVOICE_BATCHES_TYPE (BATCH_TYPE, PERIOD_TO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS INVOICES
(
    INVOICE_ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    BATCH_ID INT UNSIGNED NOT NULL,
    USER_ID INT UNSIGNED DEFAULT NULL,
    COMPETITOR_ID INT UNSIGNED DEFAULT NULL,
    FAMILY_ID INT UNSIGNED DEFAULT NULL,
    RECIPIENT_NAME VARCHAR(128) NOT NULL,
    MESSAGE VARCHAR(128) NOT NULL,
    AMOUNT DECIMAL(10,2) NOT NULL,
    INVOICE_FEE DECIMAL(10,2) NOT NULL DEFAULT 0,
    STATUS VARCHAR(10) NOT NULL DEFAULT 'UNPAID',
    PAID_AMOUNT DECIMAL(10,2) NOT NULL DEFAULT 0,
    PAID_DATE DATETIME DEFAULT NULL,
    REMINDERS INT UNSIGNED NOT NULL DEFAULT 0,
    LAST_REMINDER_DATE DATETIME DEFAULT NULL,
    PRIMARY KEY (INVOICE_ID),
    INDEX IDX_INVOICES_BATCH (BATCH_ID),
    INDEX IDX_INVOICES_USER (USER_ID),
    INDEX IDX_INVOICES_COMPETITOR (COMPETITOR_ID),
    INDEX IDX_INVOICES_FAMILY (FAMILY_ID),
    INDEX IDX_INVOICES_STATUS (STATUS, BATCH_ID),
    CONSTRAINT FK_INVOICES_BATCH FOREIGN KEY (BATCH_ID)
    REFERENCES INVOICE_BATCHES(BATCH_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS INVOICE_ROWS
(
    ROW_ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    INVOICE_ID INT UNSIGNED NOT NULL,
    SORT_ORDER INT UNSIGNED NOT NULL DEFAULT 0,
    DESCRIPTION VARCHAR(255) NOT NULL,
    NUMBER_OF INT NOT NULL DEFAULT 1,
    TOTAL_FEE DECIMAL(10,2) NOT NULL DEFAULT 0,
    AMOUNT DECIMAL(10,2) NOT NULL DEFAULT 0,
    PRIMARY KEY (ROW_ID),
    INDEX IDX_INVOICE_ROWS_INVOICE (INVOICE_ID, SORT_ORDER),
    CONSTRAINT FK_INVOICE_ROWS_INVOICE FOREIGN KEY (INVOICE_ID)
    REFERENCES INVOICES(INVOICE_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS INVOICE_HISTORY
(
    HISTORY_ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    INVOICE_ID INT UNSIGNED NOT NULL,
    OLD_STATUS VARCHAR(10) DEFAULT NULL,
    NEW_STATUS VARCHAR(10) NOT NULL,
    OLD_PAID_AMOUNT DECIMAL(10,2) DEFAULT NULL,
    NEW_PAID_AMOUNT DECIMAL(10,2) NOT NULL DEFAULT 0,
    COMMENT VARCHAR(255) DEFAULT NULL,
    SWISH_PAYMENT_ID CHAR(32) DEFAULT NULL,
    CHANGED_BY_USER_ID INT UNSIGNED DEFAULT NULL,
    CRE_DATE DATETIME NOT NULL,
    PRIMARY KEY (HISTORY_ID),
    INDEX IDX_INVOICE_HISTORY_INVOICE (INVOICE_ID),
    CONSTRAINT FK_INVOICE_HISTORY_INVOICE FOREIGN KEY (INVOICE_ID)
    REFERENCES INVOICES(INVOICE_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- PAYMENT_ID is the instructionUUID sent to Swish (32 hex characters).
-- STATUS CREATED, PAID, DECLINED, ERROR or CANCELLED (from Swish).
CREATE TABLE IF NOT EXISTS SWISH_PAYMENTS
(
    PAYMENT_ID CHAR(32) NOT NULL,
    INVOICE_ID INT UNSIGNED NOT NULL,
    USER_ID INT UNSIGNED NOT NULL,
    AMOUNT DECIMAL(10,2) NOT NULL,
    STATUS VARCHAR(10) NOT NULL DEFAULT 'CREATED',
    PAYMENT_REFERENCE VARCHAR(64) DEFAULT NULL,
    PAYER_ALIAS VARCHAR(32) DEFAULT NULL,
    ERROR_CODE VARCHAR(16) DEFAULT NULL,
    ERROR_MESSAGE VARCHAR(255) DEFAULT NULL,
    CRE_DATE DATETIME NOT NULL,
    DATE_PAID DATETIME DEFAULT NULL,
    UPDATE_DATE DATETIME NOT NULL,
    PRIMARY KEY (PAYMENT_ID),
    INDEX IDX_SWISH_PAYMENTS_INVOICE (INVOICE_ID, STATUS),
    CONSTRAINT FK_SWISH_PAYMENTS_INVOICE FOREIGN KEY (INVOICE_ID)
    REFERENCES INVOICES(INVOICE_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
